'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'bober-4-favorites-'));
process.env.BOBER_FAVORITES_DATA_DIR = dir;
const favorites = require('../src/favorites');
const guild = '123456789012345678', user = '987654321098765432', other = '987654321098765433';
test('ulubione 4.0: zapis, prywatność, kopie i usuwanie', t => {
  t.after(() => fs.rmSync(dir, { recursive:true, force:true }));
  assert.deepEqual(favorites.list(guild,user), []);
  const song = { kind:'file', source:'demo.wav', title:'Demo' };
  assert.equal(favorites.add(guild,user,song).count, 1);
  assert.equal(favorites.get(guild,user,1).source, 'demo.wav');
  assert.deepEqual(favorites.list(guild,other), []);
  assert.throws(() => favorites.add(guild,user,song), /już/);
  assert.throws(() => favorites.add(guild,user,{ kind:'diagnostic', source:'test.ogg' }), /nie można/);
  assert.throws(() => favorites.get(guild,user,2), /numer/);
  const copy = favorites.get(guild,user,1);
  copy.title = 'ZMIANA';
  assert.equal(favorites.get(guild,user,1).title, 'Demo');
  assert.equal(favorites.remove(guild,user,1).title, 'Demo');
  assert.deepEqual(favorites.list(guild,user), []);
  assert.throws(() => favorites.list('../oops', user), /identyfikator/);
  for (let i=0;i<30;i++) favorites.add(guild,user,{kind:'file',source:'song-'+i+'.mp3',title:'Track '+i});
  assert.equal(favorites.list(guild,user).length, 30);
  assert.throws(() => favorites.add(guild,user,{kind:'file',source:'overflow.mp3',title:'extra'}), /Limit/);
});
